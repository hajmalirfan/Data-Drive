import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { MESSAGES } from '../src/i18n/messages.js'

const CACHE_DIR = new URL('../.translation-cache/', import.meta.url)
await mkdir(CACHE_DIR, { recursive: true })

const LANGUAGES = [
  { code: 'en', label: 'English', native: 'English' },
  { code: 'hi', label: 'Hindi', native: 'हिन्दी' },
  { code: 'ta', label: 'Tamil', native: 'தமிழ்' },
  { code: 'te', label: 'Telugu', native: 'తెలుగు' },
  { code: 'kn', label: 'Kannada', native: 'ಕನ್ನಡ' },
  { code: 'ml', label: 'Malayalam', native: 'മലയാളം' },
  { code: 'mr', label: 'Marathi', native: 'मराठी' },
  { code: 'bn', label: 'Bengali', native: 'বাংলা' },
  { code: 'gu', label: 'Gujarati', native: 'ગુજરાતી' },
  { code: 'pa', label: 'Punjabi', native: 'ਪੰਜਾਬੀ' },
]

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))

async function translateBatch(texts, target) {
  const params = texts.map((text) => `q=${encodeURIComponent(text)}`).join('&')
  const url = `https://clients5.google.com/translate_a/t?client=dict-chrome-ex&sl=en&tl=${target}&${params}`
  for (let attempt = 1; attempt <= 4; attempt += 1) {
    try {
      const response = await fetch(url, {
        headers: {
          'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36',
        },
      })
      if (!response.ok) throw new Error(`HTTP ${response.status}`)
      const data = await response.json()
      if (!Array.isArray(data) || data.length !== texts.length) {
        throw new Error(`Unexpected response shape (${Array.isArray(data) ? data.length : typeof data})`)
      }
      return data
    } catch (error) {
      if (attempt === 4) throw error
      await sleep(1200 * attempt)
    }
  }
  return texts
}

async function translateAll(target) {
  const entries = Object.entries(MESSAGES)
  const output = {}
  let index = 0
  while (index < entries.length) {
    const batch = []
    let length = 0
    while (index < entries.length) {
      const [key, value] = entries[index]
      const encoded = encodeURIComponent(value).length
      if (batch.length > 0 && (length + encoded > 2600 || batch.length >= 20)) break
      batch.push([key, value])
      length += encoded + 3
      index += 1
    }
    const translated = await translateBatch(batch.map(([, value]) => value), target)
    batch.forEach(([key, value], i) => {
      const next = translated[i]
      output[key] = typeof next === 'string' && next.trim() ? next : value
    })
    process.stdout.write(`  ${target}: ${Math.min(index, entries.length)}/${entries.length}\n`)
    await sleep(280)
  }
  return output
}

const result = { en: MESSAGES }
for (const language of LANGUAGES) {
  if (language.code === 'en') continue
  const cacheFile = new URL(`${language.code}.json`, CACHE_DIR)
  try {
    const cached = JSON.parse(await readFile(cacheFile, 'utf8'))
    if (cached && Object.keys(cached).length === Object.keys(MESSAGES).length) {
      console.log(`Using cached ${language.label}`)
      result[language.code] = cached
      continue
    }
  } catch {
    // No cache yet.
  }
  console.log(`Translating ${language.label}...`)
  result[language.code] = await translateAll(language.code)
  await writeFile(cacheFile, JSON.stringify(result[language.code], null, 2), 'utf8')
}

const sortKeys = (source, target) => {
  const ordered = {}
  for (const key of Object.keys(source)) ordered[key] = target[key]
  return ordered
}

const lines = [
  '// Generated by scripts/generate-translations.mjs. Do not edit manually.',
  `export const LANGUAGES = ${JSON.stringify(LANGUAGES, null, 2)}`,
  '',
  'export const translations = {',
]
for (const language of LANGUAGES) {
  const messages = sortKeys(MESSAGES, result[language.code] || MESSAGES)
  lines.push(`  ${language.code}: ${JSON.stringify(messages, null, 2).replace(/\n/g, '\n  ')},`)
}
lines.push('}', '')

await writeFile(new URL('../src/i18n/translations.js', import.meta.url), lines.join('\n'), 'utf8')
console.log('Wrote src/i18n/translations.js')
